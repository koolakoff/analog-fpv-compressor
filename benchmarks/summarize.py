"""Publish compact experiment measurements without tracking generated media."""
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "benchmarks/results/initial"
rows = []
validation_path = RESULTS / "full-validation.json"
validation = json.loads(validation_path.read_text()) if validation_path.exists() else {}
checks = {item["id"]: item["passed"] for item in validation.get("results", [])}
for path in sorted(RESULTS.glob("*.run.json")):
    record = json.loads(path.read_text(encoding="utf-8"))
    if "spec" not in record or record.get("exit_code") != 0:
        continue
    spec = record["spec"]
    duration = float(record["output_probe"]["format"]["duration"])
    log = path.with_name(path.name.replace(".run.json", ".log")).read_text(encoding="utf-8")
    cpu = re.search(r"utime=([\d.]+)s stime=([\d.]+)s", log)
    rss = re.search(r"maxrss=(\d+)KiB", log)
    decode = RESULTS / f"{record['name']}.decode.run.json"
    verified = decode.exists() and json.loads(decode.read_text())["exit_code"] == 0
    rows.append({"id": record["name"], "codec": spec.get("codec", "libsvtav1"), "crf": spec["crf"],
                 "preset": spec.get("preset", 6), "denoise": spec.get("denoise", "off"),
                 "scale": "x".join(map(str, spec.get("scale", [640, 480]))), "bytes": record["bytes"],
                 "duration_s": duration, "wall_s": record["wall_seconds"],
                 "cpu_s": sum(map(float, cpu.groups())) if cpu else None,
                 "maxrss_kib": int(rss[1]) if rss else None,
                 "bitrate_kbps": record["bytes"] * 8 / duration / 1000,
                 "decode_ok": verified, "status": "rejected" if record.get("rejected_reason") else
                         "superseded" if record.get("superseded_by") else "current",
                 "timing": "PASS" if checks.get(record["name"]) is True else
                           "FAIL" if checks.get(record["name"]) is False else "not checked"})
with (RESULTS / "encoding-summary.csv").open("w", newline="", encoding="utf-8") as file:
    writer = csv.DictWriter(file, fieldnames=list(rows[0]))
    writer.writeheader()
    writer.writerows(rows)
lines = ["# DVR encoding measurements", "",
         "Research date: 2026-10-04. Generated by `benchmarks/summarize.py` from successful run JSON and logs.",
         "Decimal MB (1 MB = 1000000 bytes). File size includes MKV overhead; audio is removed.",
         "Wall time includes FFmpeg startup, excluding the separate decode validation. CPU is FFmpeg utime plus stime.",
         "Equal CRF values across codecs do not imply equal quality. Context and visual limits: [research journal](experiments-2026-10-04.md).", "",
         "Decode success alone does not establish interval/count correctness. Superseded runs must not be used as final cut results.", "",
         "| Run | CRF / preset | HQDN3D | Resolution | MB | Duration, s | Wall, s | CPU, s | kbit/s | Decode | Timing | Status |",
         "|---|---|---|---|---:|---:|---:|---:|---:|---|---|---|"]
for r in rows:
    lines.append(f"| {r['id']} | {r['crf']} / {r['preset']} | {r['denoise']} | {r['scale']} | "
                 f"{r['bytes']/1e6:.3f} | {r['duration_s']:.3f} | {r['wall_s']:.2f} | "
                 f"{r['cpu_s']:.2f} | {r['bitrate_kbps']:.1f} | {'OK' if r['decode_ok'] else 'PENDING'} | {r['timing']} | {r['status']} |")
(ROOT / "docs/research/encoding-table-2026-10-04.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Summarized {len(rows)} successful encodes")
